//! `cargo xtask gen-mapping [--check]`: generates `docs/src/mapping.md`, the
//! LVGL C API -> ferrovgl table, from the upstream public headers and the
//! upstream function names cited in ferrovgl doc comments.
//!
//! Upstream side: every `lv_*` function prototype or `static inline`
//! definition in `tests/upstream/lvgl/include/lvgl/**/*.h` (the v9.6.0 public
//! headers), plus any `src/widgets/**/lv_*.h` that is not a private header or
//! a forwarder to `include/lvgl`. The `#if` stack and `@deprecated` /
//! `LV_DEPRECATED` markers of each prototype are kept.
//!
//! Rust side: the `mod` tree of every crate under `crates/` is walked from
//! `src/lib.rs` (`#[cfg(test)]` items are skipped). A `fn`, `const` or
//! `static` maps the C functions cited at the *start* of the first paragraph
//! of its doc comment, e.g. `` /// `lv_obj_set_width()` `` or
//! `` /// `lv_label_set_text_fmt/vfmt()`, ... ``. Items generated by table
//! macros (`macro_rules!` with a single `$( ( $a:ident, .. ) ),*` arm, and
//! callback tables such as `style_props!(gen_style_setters)`) are expanded
//! first, so the generated style accessors count too. Comment sentences
//! (doc or plain) that cite an `lv_*()` function together with "not ported",
//! "not provided", ... are kept as notes for functions that stay unmapped.
//!
//! The output is sorted and contains no timestamps, so `--check` can compare
//! it byte for byte.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::Result;

const UPSTREAM_INCLUDE: &str = "tests/upstream/lvgl/include/lvgl";
const UPSTREAM_SRC_WIDGETS: &str = "tests/upstream/lvgl/src/widgets";
const CRATES_DIR: &str = "crates";
const OUTPUT: &str = "docs/src/mapping.md";

/// Regenerates (or, with `check`, verifies) `docs/src/mapping.md`.
pub fn gen_mapping(root: &Path, check: bool) -> Result<()> {
    let include = root.join(UPSTREAM_INCLUDE);
    if !include.is_dir() {
        return Err(format!(
            "{} is missing; run `cargo xtask refimgs sync` first",
            include.display()
        )
        .into());
    }
    let headers = scan_upstream(root)?;
    let rust = scan_workspace(&root.join(CRATES_DIR), root)?;
    let report = build_report(&headers, &rust);
    let page = render(&report);
    for m in &report.modules {
        println!(
            "{}: {}/{} mapped",
            m.path,
            m.count(Status::is_mapped),
            m.rows.len()
        );
    }
    println!("{}", report.summary_line());

    let out = root.join(OUTPUT);
    let existing = std::fs::read_to_string(&out).unwrap_or_default();
    if existing == page {
        return Ok(());
    }
    if check {
        return Err(format!("{OUTPUT} is out of date; run `cargo xtask gen-mapping`").into());
    }
    std::fs::write(&out, page)?;
    println!("wrote {}", out.display());
    Ok(())
}

