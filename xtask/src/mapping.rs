#[derive(Clone, Debug, PartialEq, Eq)]
enum Status {
    Mapped { deprecated: bool },
    Internal,
    Excluded(String),
    NotPorted(String),
}

impl Status {
    fn is_mapped(&self) -> bool {
        matches!(self, Status::Mapped { .. })
    }
    fn is_internal(&self) -> bool {
        matches!(self, Status::Internal)
    }
    fn is_excluded(&self) -> bool {
        matches!(self, Status::Excluded(_))
    }
    fn is_not_ported(&self) -> bool {
        matches!(self, Status::NotPorted(_))
    }
}

#[derive(Clone, Debug)]
struct Row {
    name: String,
    /// Guard conditions beyond the ones shared by the whole header.
    guard: Vec<String>,
    /// `(path, cfgs beyond the module-wide ones)`.
    rust: Vec<(String, Vec<String>)>,
    status: Status,
    /// A `#define` alias of another function.
    alias: bool,
}

#[derive(Clone, Debug)]
struct Module {
    path: String,
    guard: Vec<String>,
    cfgs: Vec<String>,
    note: Option<(NoteKind, &'static str)>,
    rows: Vec<Row>,
}

impl Module {
    fn count(&self, f: fn(&Status) -> bool) -> usize {
        self.rows.iter().filter(|r| f(&r.status)).count()
    }
}

#[derive(Clone, Debug)]
struct Report {
    modules: Vec<Module>,
}

impl Report {
    fn total(&self, f: fn(&Status) -> bool) -> usize {
        self.modules.iter().map(|m| m.count(f)).sum()
    }

    fn summary_line(&self) -> String {
        let total: usize = self.modules.iter().map(|m| m.rows.len()).sum();
        let mapped = self.total(Status::is_mapped);
        let pct = if total == 0 {
            0.0
        } else {
            mapped as f64 * 100.0 / total as f64
        };
        let aliases = self
            .modules
            .iter()
            .flat_map(|m| &m.rows)
            .filter(|r| r.alias)
            .count();
        let what = if aliases == 0 {
            "upstream public functions".to_string()
        } else {
            format!("upstream public functions and aliases ({aliases} deprecated aliases)")
        };
        format!(
            "Overall: {mapped}/{total} {what} mapped ({pct:.1}%); {} crate-internal, {} excluded, {} not ported.",
            self.total(Status::is_internal),
            self.total(Status::is_excluded),
            self.total(Status::is_not_ported),
        )
    }
}

fn build_report(headers: &[Header], rust: &RustIndex) -> Report {
    let mut by_name: BTreeMap<&str, Vec<&RustItem>> = BTreeMap::new();
    for item in &rust.items {
        for c in &item.cites {
            by_name.entry(c.as_str()).or_default().push(item);
        }
    }
    let mut headers: Vec<&Header> = headers.iter().collect();
    headers.sort_by_key(|h| (category_rank(&h.path), h.path.clone()));
    let mut seen = BTreeSet::new();
    let mut modules = Vec::new();
    for h in headers {
        let funcs: Vec<&CFunc> = h.funcs.iter().filter(|f| seen.insert(f.name.clone())).collect();
        if funcs.is_empty() {
            continue;
        }
        let guard = common_prefix(funcs.iter().map(|f| f.guard.as_slice()));
        let note = header_note(&h.path);
        let mut rows = Vec::new();
        for f in &funcs {
            let items = by_name
                .get(f.name.as_str())
                .map(Vec::as_slice)
                .unwrap_or_default();
            let public: Vec<&RustItem> = items
                .iter()
                .copied()
                .filter(|i| rust.is_public(i) && !i.stub)
                .collect();
            let stubs: Vec<&RustItem> = items.iter().copied().filter(|i| i.stub).collect();
            // An alias row points at the Rust items of the function it names.
            let target: Vec<&RustItem> = f
                .alias_of
                .as_deref()
                .and_then(|t| by_name.get(t))
                .map(|v| {
                    v.iter()
                        .copied()
                        .filter(|i| rust.is_public(i) && !i.stub)
                        .collect()
                })
                .unwrap_or_default();
            let excluded_header = matches!(note, Some((NoteKind::Excluded, _)));
            let shown = if !public.is_empty() {
                public.clone()
            } else if !stubs.is_empty() {
                stubs.clone()
            } else if f.alias_of.is_some() {
                target
            } else if excluded_header {
                Vec::new()
            } else {
                items.to_vec()
            };
            let status = if !public.is_empty() {
                Status::Mapped {
                    deprecated: f.deprecated || public.iter().all(|i| i.deprecated),
                }
            } else if !stubs.is_empty() {
                Status::NotPorted("declared as a `todo!()` stub".into())
            } else if let Some(t) = &f.alias_of {
                Status::Excluded(format!("deprecated alias of `{t}()`"))
            } else if let Some((NoteKind::Excluded, why)) = note {
                Status::Excluded(why.to_string())
            } else if !items.is_empty() {
                Status::Internal
            } else if f.deprecated {
                Status::Excluded("deprecated upstream".into())
            } else if f.va_list {
                Status::Excluded("C `va_list` variant".into())
            } else if let Some(files) = rust.notes.get(&f.name) {
                let files: Vec<String> = files.iter().map(|p| format!("`{p}`")).collect();
                Status::NotPorted(format!("noted in {}", files.join(", ")))
            } else if let Some((NoteKind::Planned, why)) = note {
                Status::NotPorted(why.to_string())
            } else {
                Status::NotPorted(String::new())
            };
            rows.push(Row {
                name: f.name.clone(),
                guard: f.guard[guard.len()..].to_vec(),
                rust: shown.iter().map(|i| (i.path.clone(), i.cfgs.clone())).collect(),
                status,
                alias: f.alias_of.is_some(),
            });
        }
        // Rust cfgs shared by every listed item become a module-wide line.
        let mut lists = rows.iter().flat_map(|r| r.rust.iter().map(|(_, c)| c));
        let mut cfgs: Vec<String> = lists.next().cloned().unwrap_or_default();
        for l in lists {
            cfgs.retain(|c| l.contains(c));
        }
        for r in &mut rows {
            for (_, c) in &mut r.rust {
                c.retain(|x| !cfgs.contains(x));
            }
            r.rust.sort();
            r.rust.dedup();
        }
        modules.push(Module {
            path: h.path.clone(),
            guard,
            cfgs,
            note,
            rows,
        });
    }
    Report { modules }
}

fn common_prefix<'a>(mut lists: impl Iterator<Item = &'a [String]>) -> Vec<String> {
    let Some(first) = lists.next() else {
        return Vec::new();
    };
    let mut prefix = first.to_vec();
    for l in lists {
        let n = prefix.iter().zip(l).take_while(|(a, b)| a == b).count();
        prefix.truncate(n);
    }
    prefix
}

