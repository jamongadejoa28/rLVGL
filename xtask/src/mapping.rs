#[derive(Clone, Debug, PartialEq, Eq)]
enum Tok {
    Ident(String),
    /// String literal contents (escapes kept as written).
    Str(String),
    /// Numbers, character literals and lifetimes.
    Lit(String),
    Punct(char),
    Doc {
        inner: bool,
        text: String,
    },
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Tree {
    Tok(Tok),
    /// A `(`, `[` or `{` group.
    Group(char, Vec<Tree>),
}

struct Lexer {
    c: Vec<char>,
    i: usize,
    out: Vec<Tok>,
    /// Plain (non-doc) comments; consecutive `//` lines form one entry.
    comments: Vec<String>,
    /// `out.len()` right after the last `//` comment.
    line_comment_mark: Option<usize>,
}

impl Lexer {
    fn at(&self, k: usize) -> char {
        self.c.get(k).copied().unwrap_or('\0')
    }

    fn run(mut self) -> (Vec<Tok>, Vec<String>) {
        while self.i < self.c.len() {
            self.step();
        }
        (self.out, self.comments)
    }

    fn step(&mut self) {
        let i = self.i;
        let ch = self.c[i];
        if ch.is_whitespace() {
            self.i += 1;
        } else if ch == '/' && self.at(i + 1) == '/' {
            let mut j = i;
            while j < self.c.len() && self.c[j] != '\n' {
                j += 1;
            }
            let line: String = self.c[i..j].iter().collect();
            self.i = j;
            if let Some(rest) = line.strip_prefix("///") {
                if !rest.starts_with('/') {
                    self.out.push(Tok::Doc {
                        inner: false,
                        text: doc_text(rest),
                    });
                }
            } else if let Some(rest) = line.strip_prefix("//!") {
                self.out.push(Tok::Doc {
                    inner: true,
                    text: doc_text(rest),
                });
            } else {
                let text = line.trim_start_matches('/').trim();
                match self.comments.last_mut() {
                    Some(last) if self.line_comment_mark == Some(self.out.len()) => {
                        last.push(' ');
                        last.push_str(text);
                    }
                    _ => self.comments.push(text.to_string()),
                }
                self.line_comment_mark = Some(self.out.len());
            }
        } else if ch == '/' && self.at(i + 1) == '*' {
            let mut j = i;
            let mut depth = 0;
            while j < self.c.len() {
                if self.c[j] == '/' && self.at(j + 1) == '*' {
                    depth += 1;
                    j += 2;
                } else if self.c[j] == '*' && self.at(j + 1) == '/' {
                    depth -= 1;
                    j += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    j += 1;
                }
            }
            let body: String = self.c[i..j.min(self.c.len())].iter().collect();
            self.i = j;
            let inner = body.starts_with("/*!");
            if inner || (body.starts_with("/**") && !body.starts_with("/***") && body != "/**/") {
                let text = body.get(3..).unwrap_or_default();
                let text = text.strip_suffix("*/").unwrap_or(text);
                for l in text.lines() {
                    let l = l.trim().trim_start_matches('*');
                    self.out.push(Tok::Doc {
                        inner,
                        text: doc_text(l),
                    });
                }
            } else {
                let text = body.get(2..).unwrap_or_default();
                self.comments
                    .push(squash(text.strip_suffix("*/").unwrap_or(text)));
                self.line_comment_mark = None;
            }
        } else if let Some((hashes, start)) = self.raw_string_start() {
            let mut j = start;
            while j < self.c.len() && !(self.c[j] == '"' && (0..hashes).all(|h| self.at(j + 1 + h) == '#')) {
                j += 1;
            }
            self.out
                .push(Tok::Str(self.c[start..j.min(self.c.len())].iter().collect()));
            self.i = j + 1 + hashes;
        } else if ch == '"' || (ch == 'b' && self.at(i + 1) == '"') {
            let start = if ch == 'b' { i + 2 } else { i + 1 };
            let mut j = start;
            while j < self.c.len() && self.c[j] != '"' {
                j += if self.c[j] == '\\' { 2 } else { 1 };
            }
            self.out
                .push(Tok::Str(self.c[start..j.min(self.c.len())].iter().collect()));
            self.i = j + 1;
        } else if ch == '\'' || (ch == 'b' && self.at(i + 1) == '\'') {
            let q = if ch == 'b' { i + 1 } else { i };
            let mut j = q + 1;
            if self.at(j) == '\\' {
                j += 2;
                while j < self.c.len() && self.c[j] != '\'' {
                    j += 1;
                }
                j += 1;
            } else if self.at(j + 1) == '\'' {
                j += 2;
            } else {
                // A lifetime.
                while j < self.c.len() && (self.c[j].is_alphanumeric() || self.c[j] == '_') {
                    j += 1;
                }
            }
            self.out
                .push(Tok::Lit(self.c[i..j.min(self.c.len())].iter().collect()));
            self.i = j;
        } else if ch == 'r' && self.at(i + 1) == '#' && is_ident_start(self.at(i + 2)) {
            self.i += 2;
            self.ident();
        } else if is_ident_start(ch) {
            self.ident();
        } else if ch.is_ascii_digit() {
            let mut j = i;
            while j < self.c.len()
                && (self.c[j].is_alphanumeric()
                    || self.c[j] == '_'
                    || (self.c[j] == '.' && self.at(j + 1).is_ascii_digit()))
            {
                j += 1;
            }
            self.out.push(Tok::Lit(self.c[i..j].iter().collect()));
            self.i = j;
        } else {
            self.out.push(Tok::Punct(ch));
            self.i += 1;
        }
    }

    /// `r"`, `r#"`, `br"`, `br#"`: the number of `#` and the content start.
    fn raw_string_start(&self) -> Option<(usize, usize)> {
        let i = self.i;
        let mut j = match (self.c[i], self.at(i + 1)) {
            ('r', '"' | '#') => i + 1,
            ('b', 'r') if matches!(self.at(i + 2), '"' | '#') => i + 2,
            _ => return None,
        };
        let mut hashes = 0;
        while self.at(j) == '#' {
            hashes += 1;
            j += 1;
        }
        (self.at(j) == '"').then_some((hashes, j + 1))
    }

    fn ident(&mut self) {
        let start = self.i;
        while self.i < self.c.len() && (self.c[self.i].is_alphanumeric() || self.c[self.i] == '_') {
            self.i += 1;
        }
        self.out.push(Tok::Ident(self.c[start..self.i].iter().collect()));
    }
}

fn is_ident_start(c: char) -> bool {
    c.is_alphabetic() || c == '_'
}

/// A doc comment line without the one leading space rustdoc strips.
fn doc_text(rest: &str) -> String {
    rest.strip_prefix(' ').unwrap_or(rest).trim_end().to_string()
}

/// The tokens and the plain comments of a Rust source file.
fn lex(src: &str) -> (Vec<Tok>, Vec<String>) {
    Lexer {
        c: src.chars().collect(),
        i: 0,
        out: Vec::new(),
        comments: Vec::new(),
        line_comment_mark: None,
    }
    .run()
}

#[cfg(test)]
fn rust_trees(src: &str) -> Vec<Tree> {
    build_trees(lex(src).0)
}

fn build_trees(toks: Vec<Tok>) -> Vec<Tree> {
    let mut stack: Vec<(char, Vec<Tree>)> = vec![('\0', Vec::new())];
    fn close(stack: &mut Vec<(char, Vec<Tree>)>) {
        if stack.len() > 1 {
            let (open, kids) = stack.pop().unwrap_or_default();
            if let Some(top) = stack.last_mut() {
                top.1.push(Tree::Group(open, kids));
            }
        }
    }
    for t in toks {
        match t {
            Tok::Punct(open @ ('(' | '[' | '{')) => stack.push((open, Vec::new())),
            Tok::Punct(')' | ']' | '}') => close(&mut stack),
            t => {
                if let Some(top) = stack.last_mut() {
                    top.1.push(Tree::Tok(t));
                }
            }
        }
    }
    while stack.len() > 1 {
        close(&mut stack);
    }
    stack.pop().map(|s| s.1).unwrap_or_default()
}

/// Where an item lives.
#[derive(Clone, Debug)]
struct Ctx {
    krate: String,
    /// Workspace-relative path of the source file.
    file: String,
    /// Directory of the child module files.
    dir: PathBuf,
    module: Vec<String>,
    /// Every module of `module` is `pub`.
    public: bool,
    cfgs: Vec<String>,
    owner: Option<Owner>,
}

/// The `impl` or `trait` an item belongs to.
#[derive(Clone, Debug)]
struct Owner {
    name: String,
    /// Items of trait impls and trait definitions need no `pub`.
    trait_like: bool,
    /// For a trait definition: whether the trait itself is public.
    trait_public: bool,
}

/// A Rust item whose doc comment cites upstream functions.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct RustItem {
    /// `Type::name` for associated items, `crate::module::name` otherwise.
    path: String,
    krate: String,
    owner: Option<String>,
    /// Visible outside its crate, assuming the owner type is public.
    public: bool,
    /// `cfg` predicates of the item and everything around it.
    cfgs: Vec<String>,
    deprecated: bool,
    /// The body is a `todo!()` / `unimplemented!()` skeleton.
    stub: bool,
    cites: Vec<String>,
}

#[derive(Clone, Debug)]
enum MacroKind {
    /// `( $( ( $a:frag, $b:frag, .. ) ),* $(,)? ) => { body }`.
    Table { params: Vec<String>, body: Vec<Tree> },
    /// `( $cb:ident ) => { $cb! { rows } }`.
    Rows { rows: Vec<Tree> },
}

#[derive(Clone, Debug)]
struct Invocation {
    name: String,
    args: Vec<Tree>,
    ctx: Ctx,
}

/// Everything the Rust scan finds.
#[derive(Debug, Default)]
struct RustIndex {
    items: Vec<RustItem>,
    /// Upstream function -> files whose docs say it is not ported.
    notes: BTreeMap<String, BTreeSet<String>>,
    /// `(crate, name)` -> type or trait visibility.
    types: BTreeMap<(String, String), bool>,
    macros: BTreeMap<String, Vec<(String, MacroKind)>>,
    invocations: Vec<Invocation>,
    pending: Vec<(PathBuf, Ctx)>,
}

impl RustIndex {
    fn is_public(&self, item: &RustItem) -> bool {
        item.public
            && item.owner.as_ref().is_none_or(|o| {
                self.types
                    .get(&(item.krate.clone(), o.clone()))
                    .copied()
                    .unwrap_or(true)
            })
    }
}

fn scan_workspace(crates: &Path, root: &Path) -> Result<RustIndex> {
    let mut idx = RustIndex::default();
    let mut dirs: Vec<PathBuf> = std::fs::read_dir(crates)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.join("src/lib.rs").is_file())
        .collect();
    dirs.sort();
    for dir in dirs {
        let manifest = std::fs::read_to_string(dir.join("Cargo.toml"))?;
        let name = package_name(&manifest)
            .unwrap_or_else(|| dir.file_name().unwrap_or_default().to_string_lossy().into_owned());
        let ctx = Ctx {
            krate: name.replace('-', "_"),
            file: String::new(),
            dir: dir.join("src"),
            module: Vec::new(),
            public: true,
            cfgs: Vec::new(),
            owner: None,
        };
        idx.pending.push((dir.join("src/lib.rs"), ctx));
        while let Some((file, mut ctx)) = idx.pending.pop() {
            let Ok(text) = std::fs::read_to_string(&file) else {
                continue; // a `mod` whose file does not exist (e.g. behind an unknown `#[path]`)
            };
            ctx.file = rel(&file, root);
            let (toks, comments) = lex(&text);
            parse_items(&build_trees(toks), &ctx, &mut idx);
            for c in comments {
                collect_notes(&[c], &ctx.file, &mut idx);
            }
        }
    }
    expand_invocations(&mut idx);
    idx.items.sort();
    idx.items.dedup();
    Ok(idx)
}

fn package_name(manifest: &str) -> Option<String> {
    let mut in_package = false;
    for line in manifest.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
        } else if in_package && let Some(v) = line.strip_prefix("name") {
            let v = v.trim_start().strip_prefix('=')?.trim().trim_matches('"');
            return Some(v.to_string());
        }
    }
    None
}

fn expand_invocations(idx: &mut RustIndex) {
    for _round in 0..8 {
        let invocations = std::mem::take(&mut idx.invocations);
        if invocations.is_empty() {
            return;
        }
        for inv in invocations {
            if let Some(trees) = expand(&inv, &idx.macros, 0) {
                parse_items(&trees, &inv.ctx, idx);
            }
        }
    }
}

fn find_macro<'a>(
    macros: &'a BTreeMap<String, Vec<(String, MacroKind)>>,
    inv: &Invocation,
) -> Option<&'a MacroKind> {
    let defs = macros.get(&inv.name)?;
    defs.iter()
        .find(|(k, _)| *k == inv.ctx.krate)
        .or_else(|| defs.first())
        .map(|(_, m)| m)
}

fn expand(
    inv: &Invocation,
    macros: &BTreeMap<String, Vec<(String, MacroKind)>>,
    depth: u32,
) -> Option<Vec<Tree>> {
    if depth > 4 {
        return None;
    }
    match find_macro(macros, inv)? {
        MacroKind::Table { params, body } => {
            let rows: Vec<Vec<Vec<Tree>>> = split_commas(&inv.args)
                .into_iter()
                .filter_map(|piece| match piece.as_slice() {
                    [Tree::Group('(', fields)] => Some(split_commas(fields)),
                    _ => None,
                })
                .collect();
            Some(subst_repetitions(body, params, &rows))
        }
        MacroKind::Rows { rows } => {
            let [Tree::Tok(Tok::Ident(cb))] = inv.args.as_slice() else {
                return None;
            };
            let next = Invocation {
                name: cb.clone(),
                args: rows.clone(),
                ctx: inv.ctx.clone(),
            };
            expand(&next, macros, depth + 1)
        }
    }
}

/// Splits a token list at its top-level commas (empty pieces dropped).
fn split_commas(trees: &[Tree]) -> Vec<Vec<Tree>> {
    let mut out = vec![Vec::new()];
    for t in trees {
        if *t == Tree::Tok(Tok::Punct(',')) {
            out.push(Vec::new());
        } else if let Some(last) = out.last_mut() {
            last.push(t.clone());
        }
    }
    out.retain(|p| !p.is_empty());
    out
}

/// Expands every `$( .. )*` / `$( .. ),*` of a macro body once per row.
fn subst_repetitions(body: &[Tree], params: &[String], rows: &[Vec<Vec<Tree>>]) -> Vec<Tree> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < body.len() {
        if body[i] == Tree::Tok(Tok::Punct('$'))
            && let Some(Tree::Group('(', rep)) = body.get(i + 1)
        {
            let mut j = i + 2;
            let mut sep = None;
            if let Some(Tree::Tok(Tok::Punct(p))) = body.get(j)
                && !matches!(p, '*' | '+' | '?')
            {
                sep = Some(body[j].clone());
                j += 1;
            }
            if matches!(body.get(j), Some(Tree::Tok(Tok::Punct('*' | '+' | '?')))) {
                for (n, row) in rows.iter().enumerate() {
                    if n > 0
                        && let Some(s) = &sep
                    {
                        out.push(s.clone());
                    }
                    let bind: BTreeMap<&str, &Vec<Tree>> =
                        params.iter().map(String::as_str).zip(row.iter()).collect();
                    out.extend(subst_vars(rep, &bind));
                }
                i = j + 1;
                continue;
            }
        }
        match &body[i] {
            Tree::Group(d, kids) => out.push(Tree::Group(*d, subst_repetitions(kids, params, rows))),
            t => out.push(t.clone()),
        }
        i += 1;
    }
    out
}

fn subst_vars(trees: &[Tree], bind: &BTreeMap<&str, &Vec<Tree>>) -> Vec<Tree> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < trees.len() {
        if trees[i] == Tree::Tok(Tok::Punct('$'))
            && let Some(Tree::Tok(Tok::Ident(name))) = trees.get(i + 1)
        {
            if let Some(v) = bind.get(name.as_str()) {
                out.extend(v.iter().cloned());
            } else {
                out.push(Tree::Tok(Tok::Ident(name.clone()))); // `$crate`
            }
            i += 2;
            continue;
        }
        match &trees[i] {
            Tree::Group(d, kids) => out.push(Tree::Group(*d, subst_vars(kids, bind))),
            t => out.push(t.clone()),
        }
        i += 1;
    }
    out
}

fn ident_at(trees: &[Tree], k: usize) -> Option<&str> {
    match trees.get(k) {
        Some(Tree::Tok(Tok::Ident(s))) => Some(s),
        _ => None,
    }
}

fn is_punct(t: Option<&Tree>, c: char) -> bool {
    matches!(t, Some(Tree::Tok(Tok::Punct(p))) if *p == c)
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Vis {
    Pub,
    Restricted,
    Private,
}

fn parse_items(trees: &[Tree], ctx: &Ctx, idx: &mut RustIndex) {
    let mut ctx = ctx.clone();
    let mut attrs: Vec<&[Tree]> = Vec::new();
    let mut docs: Vec<String> = Vec::new();
    let mut inner_docs: Vec<String> = Vec::new();
    let mut i = 0;
    while i < trees.len() {
        match &trees[i] {
            Tree::Tok(Tok::Doc { inner: true, text }) => {
                inner_docs.push(text.clone());
                i += 1;
                continue;
            }
            Tree::Tok(Tok::Doc { inner: false, text }) => {
                docs.push(text.clone());
                i += 1;
                continue;
            }
            Tree::Tok(Tok::Punct('#')) => {
                if is_punct(trees.get(i + 1), '!')
                    && let Some(Tree::Group('[', a)) = trees.get(i + 2)
                {
                    if ident_at(a, 0) == Some("cfg")
                        && let Some(Tree::Group('(', p)) = a.get(1)
                    {
                        ctx.cfgs.push(render_cfg(p));
                    }
                    i += 3;
                    continue;
                }
                if let Some(Tree::Group('[', a)) = trees.get(i + 1) {
                    attrs.push(a);
                    i += 2;
                    continue;
                }
                i += 1;
                continue;
            }
            Tree::Tok(Tok::Punct(';')) => {
                attrs.clear();
                docs.clear();
                i += 1;
                continue;
            }
            _ => {}
        }
        let mut attr = ItemAttrs {
            docs: std::mem::take(&mut docs),
            ..ItemAttrs::default()
        };
        for a in attrs.drain(..) {
            match ident_at(a, 0) {
                Some("cfg") => {
                    if let Some(Tree::Group('(', p)) = a.get(1) {
                        if is_test_cfg(p) {
                            attr.test_only = true;
                        } else {
                            attr.cfgs.push(render_cfg(p));
                        }
                    }
                }
                Some("deprecated") => attr.deprecated = true,
                Some("doc") => {
                    if let Some(text) = eval_doc_attr(&a[1..]) {
                        attr.docs.extend(text.lines().map(str::to_string));
                    }
                }
                Some("path") => {
                    if let Some(Tree::Tok(Tok::Str(p))) = a.get(2) {
                        attr.path = Some(p.clone());
                    }
                }
                _ => {}
            }
        }
        collect_notes(&attr.docs, &ctx.file, idx);
        let end = item_end(trees, i);
        if !attr.test_only {
            handle_item(&trees[i..end], &attr, &ctx, idx);
        }
        i = end;
    }
    collect_notes(&inner_docs, &ctx.file, idx);
}

#[derive(Debug, Default)]
struct ItemAttrs {
    docs: Vec<String>,
    cfgs: Vec<String>,
    deprecated: bool,
    test_only: bool,
    path: Option<String>,
}

/// Index of the qualifiers and keyword of an item: `(vis, keyword index)`.
fn item_head(item: &[Tree]) -> (Vis, usize) {
    let (vis, mut k) = match (ident_at(item, 0), item.get(1)) {
        (Some("pub"), Some(Tree::Group('(', _))) => (Vis::Restricted, 2),
        (Some("pub"), _) => (Vis::Pub, 1),
        _ => (Vis::Private, 0),
    };
    loop {
        match ident_at(item, k) {
            Some("const") if matches!(ident_at(item, k + 1), Some("fn" | "unsafe" | "async" | "extern")) => {
                k += 1
            }
            Some("unsafe" | "async" | "default") => k += 1,
            Some("extern") if matches!(item.get(k + 1), Some(Tree::Tok(Tok::Str(_)))) => k += 2,
            _ => return (vis, k),
        }
    }
}

/// The index after the item that starts at `start`.
fn item_end(trees: &[Tree], start: usize) -> usize {
    let item = &trees[start..];
    let (_, k) = item_head(item);
    let semicolon_only = matches!(
        ident_at(item, k),
        Some("const" | "static" | "use" | "type" | "let")
    );
    for (n, t) in item.iter().enumerate() {
        match t {
            Tree::Tok(Tok::Punct(';')) => return start + n + 1,
            Tree::Group('{', _) if !semicolon_only => return start + n + 1,
            // `name! ( .. );` / `name! [ .. ];` at item level.
            Tree::Group('(' | '[', _) if n > 0 && is_punct(item.get(n - 1), '!') && k == 0 => {
                let skip = usize::from(is_punct(item.get(n + 1), ';'));
                return start + n + 1 + skip;
            }
            _ => {}
        }
    }
    trees.len()
}

fn handle_item(item: &[Tree], attr: &ItemAttrs, ctx: &Ctx, idx: &mut RustIndex) {
    let (vis, k) = item_head(item);
    let mut cfgs = ctx.cfgs.clone();
    cfgs.extend(attr.cfgs.iter().cloned());
    match ident_at(item, k) {
        Some("fn") => {
            if let Some(name) = ident_at(item, k + 1) {
                let stub = matches!(item.last(), Some(Tree::Group('{', body)) if contains_todo(body));
                record(name, attr, vis, cfgs, stub, ctx, idx);
            }
        }
        Some("const" | "static") => {
            let n = if ident_at(item, k + 1) == Some("mut") {
                k + 2
            } else {
                k + 1
            };
            if let Some(name) = ident_at(item, n)
                && name != "_"
            {
                record(name, attr, vis, cfgs, false, ctx, idx);
            }
        }
        Some("struct" | "enum" | "union" | "type") => {
            if let Some(name) = ident_at(item, k + 1) {
                idx.types
                    .insert((ctx.krate.clone(), name.to_string()), vis == Vis::Pub);
            }
        }
        Some("trait") => {
            let Some(name) = ident_at(item, k + 1) else { return };
            let public = vis == Vis::Pub && ctx.public;
            idx.types
                .insert((ctx.krate.clone(), name.to_string()), vis == Vis::Pub);
            if let Some(Tree::Group('{', body)) = item.last() {
                let owner = Owner {
                    name: name.to_string(),
                    trait_like: true,
                    trait_public: public,
                };
                let child = Ctx {
                    cfgs,
                    owner: Some(owner),
                    ..ctx.clone()
                };
                parse_items(body, &child, idx);
            }
        }
        Some("impl") => {
            let Some(Tree::Group('{', body)) = item.last() else {
                return;
            };
            let Some((name, trait_impl)) = impl_owner(&item[k + 1..item.len() - 1]) else {
                return;
            };
            let owner = Owner {
                name,
                trait_like: trait_impl,
                trait_public: true,
            };
            let child = Ctx {
                cfgs,
                owner: Some(owner),
                ..ctx.clone()
            };
            parse_items(body, &child, idx);
        }
        Some("mod") => {
            let Some(name) = ident_at(item, k + 1) else { return };
            let mut module = ctx.module.clone();
            module.push(name.to_string());
            let child = Ctx {
                dir: ctx.dir.join(name),
                module,
                public: ctx.public && vis == Vis::Pub,
                cfgs,
                owner: None,
                ..ctx.clone()
            };
            match item.last() {
                Some(Tree::Group('{', body)) => parse_items(body, &child, idx),
                _ => {
                    let file = match &attr.path {
                        Some(p) => ctx.dir.join(p),
                        None if ctx.dir.join(format!("{name}.rs")).is_file() => {
                            ctx.dir.join(format!("{name}.rs"))
                        }
                        None => ctx.dir.join(name).join("mod.rs"),
                    };
                    idx.pending.push((file, child));
                }
            }
        }
        Some("macro_rules") => {
            if let (Some(name), Some(Tree::Group(_, body))) = (ident_at(item, k + 2), item.get(k + 3))
                && let Some(kind) = parse_macro(body)
            {
                idx.macros
                    .entry(name.to_string())
                    .or_default()
                    .push((ctx.krate.clone(), kind));
            }
        }
        _ => {
            // `path::name! { .. }` / `name!( .. );`
            if let Some(bang) = item.iter().position(|t| is_punct(Some(t), '!'))
                && bang > 0
                && let (Some(name), Some(Tree::Group(_, args))) =
                    (ident_at(item, bang - 1), item.get(bang + 1))
                && item[..bang]
                    .iter()
                    .all(|t| matches!(t, Tree::Tok(Tok::Ident(_) | Tok::Punct(':'))))
            {
                let ctx = Ctx { cfgs, ..ctx.clone() };
                idx.invocations.push(Invocation {
                    name: name.to_string(),
                    args: args.clone(),
                    ctx,
                });
            }
        }
    }
}

fn record(
    name: &str,
    attr: &ItemAttrs,
    vis: Vis,
    cfgs: Vec<String>,
    stub: bool,
    ctx: &Ctx,
    idx: &mut RustIndex,
) {
    // The first paragraph, so that a citation list may wrap.
    let first: Vec<&str> = attr
        .docs
        .iter()
        .map(|l| l.trim())
        .skip_while(|l| l.is_empty())
        .take_while(|l| !l.is_empty())
        .collect();
    let first = first.join(" ");
    let mut cites = lead_citations(&first);
    if cites.is_empty() {
        cites.extend(trailing_citation(&first, name));
    }
    if cites.is_empty() {
        return;
    }
    let (path, public, owner) = match &ctx.owner {
        Some(o) if o.trait_like => (
            format!("{}::{name}", o.name),
            o.trait_public,
            Some(o.name.clone()),
        ),
        Some(o) => (
            format!("{}::{name}", o.name),
            vis == Vis::Pub,
            Some(o.name.clone()),
        ),
        None => {
            let mut p = vec![ctx.krate.clone()];
            p.extend(ctx.module.iter().cloned());
            p.push(name.to_string());
            (p.join("::"), vis == Vis::Pub && ctx.public, None)
        }
    };
    let mut cfgs = cfgs;
    cfgs.dedup();
    idx.items.push(RustItem {
        path,
        krate: ctx.krate.clone(),
        owner,
        public,
        cfgs,
        deprecated: attr.deprecated,
        stub,
        cites,
    });
}

/// `todo!` or `unimplemented!` anywhere in a function body.
fn contains_todo(trees: &[Tree]) -> bool {
    trees.iter().enumerate().any(|(n, t)| match t {
        Tree::Tok(Tok::Ident(m)) => {
            matches!(m.as_str(), "todo" | "unimplemented") && is_punct(trees.get(n + 1), '!')
        }
        Tree::Group(_, kids) => contains_todo(kids),
        _ => false,
    })
}

/// The type an `impl` header is for, and whether it is a trait impl.
fn impl_owner(header: &[Tree]) -> Option<(String, bool)> {
    let mut k = 0;
    if is_punct(header.first(), '<') {
        let mut depth = 0;
        while k < header.len() {
            match &header[k] {
                Tree::Tok(Tok::Punct('<')) => depth += 1,
                Tree::Tok(Tok::Punct('>')) if !is_punct(header.get(k.wrapping_sub(1)), '-') => {
                    depth -= 1;
                    if depth == 0 {
                        k += 1;
                        break;
                    }
                }
                _ => {}
            }
            k += 1;
        }
    }
    let rest = &header[k.min(header.len())..];
    let rest = match rest
        .iter()
        .position(|t| *t == Tree::Tok(Tok::Ident("where".into())))
    {
        Some(w) => &rest[..w],
        None => rest,
    };
    let top_level = |toks: &[Tree]| -> Vec<(usize, String)> {
        let mut depth = 0;
        let mut out = Vec::new();
        for (n, t) in toks.iter().enumerate() {
            match t {
                Tree::Tok(Tok::Punct('<')) => depth += 1,
                Tree::Tok(Tok::Punct('>')) if !is_punct(toks.get(n.wrapping_sub(1)), '-') => depth -= 1,
                Tree::Tok(Tok::Ident(s)) if depth == 0 => out.push((n, s.clone())),
                _ => {}
            }
        }
        out
    };
    let idents = top_level(rest);
    let (ty, trait_impl) = match idents.iter().find(|(_, s)| s == "for") {
        Some((n, _)) => (&rest[n + 1..], true),
        None => (rest, false),
    };
    let name = top_level(ty)
        .into_iter()
        .map(|(_, s)| s)
        .rfind(|s| !matches!(s.as_str(), "dyn" | "mut"))?;
    Some((name, trait_impl))
}

fn parse_macro(body: &[Tree]) -> Option<MacroKind> {
    let arms: Vec<&[Tree]> = body
        .split(|t| is_punct(Some(t), ';'))
        .filter(|a| !a.is_empty())
        .collect();
    let [arm] = arms.as_slice() else { return None };
    let [
        Tree::Group(_, matcher),
        Tree::Tok(Tok::Punct('=')),
        Tree::Tok(Tok::Punct('>')),
        Tree::Group(_, out),
    ] = *arm
    else {
        return None;
    };
    // `( $cb:ident ) => { $cb! { rows } }`
    if let [
        Tree::Tok(Tok::Punct('$')),
        Tree::Tok(Tok::Ident(cb)),
        Tree::Tok(Tok::Punct(':')),
        Tree::Tok(Tok::Ident(_)),
    ] = matcher.as_slice()
        && let [
            Tree::Tok(Tok::Punct('$')),
            Tree::Tok(Tok::Ident(cb2)),
            Tree::Tok(Tok::Punct('!')),
            Tree::Group(_, rows),
        ] = out.as_slice()
        && cb == cb2
    {
        return Some(MacroKind::Rows { rows: rows.clone() });
    }
    // `( $( ( $a:frag, .. ) ),* $(,)? ) => { body }`
    if let [Tree::Tok(Tok::Punct('$')), Tree::Group('(', rep), ..] = matcher.as_slice()
        && let [Tree::Group('(', fields)] = rep.as_slice()
    {
        let params: Vec<String> = split_commas(fields)
            .iter()
            .filter_map(|f| match f.as_slice() {
                [
                    Tree::Tok(Tok::Punct('$')),
                    Tree::Tok(Tok::Ident(name)),
                    Tree::Tok(Tok::Punct(':')),
                    ..,
                ] => Some(name.clone()),
                _ => None,
            })
            .collect();
        if !params.is_empty() {
            return Some(MacroKind::Table {
                params,
                body: out.clone(),
            });
        }
    }
    None
}

/// `doc = "text"` or `doc = concat!("a", stringify!(b), ..)`.
fn eval_doc_attr(rest: &[Tree]) -> Option<String> {
    match rest {
        [Tree::Tok(Tok::Punct('=')), Tree::Tok(Tok::Str(s))] => Some(s.clone()),
        [
            Tree::Tok(Tok::Punct('=')),
            Tree::Tok(Tok::Ident(c)),
            Tree::Tok(Tok::Punct('!')),
            Tree::Group('(', parts),
        ] if c == "concat" => {
            let mut out = String::new();
            for part in split_commas(parts) {
                match part.as_slice() {
                    [Tree::Tok(Tok::Str(s))] => out.push_str(s),
                    [
                        Tree::Tok(Tok::Ident(m)),
                        Tree::Tok(Tok::Punct('!')),
                        Tree::Group('(', toks),
                    ] if m == "stringify" => {
                        out.push_str(&render_tokens(toks));
                    }
                    [Tree::Tok(Tok::Ident(s) | Tok::Lit(s))] => out.push_str(s),
                    _ => return None,
                }
            }
            Some(out)
        }
        _ => None,
    }
}

fn render_tokens(trees: &[Tree]) -> String {
    let mut out = String::new();
    for t in trees {
        match t {
            Tree::Tok(Tok::Ident(s) | Tok::Lit(s)) => {
                if out.ends_with(|c: char| c.is_alphanumeric() || c == '_') {
                    out.push(' ');
                }
                out.push_str(s);
            }
            Tree::Tok(Tok::Str(s)) => {
                let _ = write!(out, "\"{s}\"");
            }
            Tree::Tok(Tok::Punct(',')) => out.push_str(", "),
            Tree::Tok(Tok::Punct(p)) => out.push(*p),
            Tree::Tok(Tok::Doc { .. }) => {}
            Tree::Group(d, kids) => {
                let close = match d {
                    '(' => ')',
                    '[' => ']',
                    _ => '}',
                };
                out.push(*d);
                out.push_str(&render_tokens(kids));
                out.push(close);
            }
        }
    }
    out
}

/// A `cfg` predicate with `feature = "x"` shortened to `x`.
fn render_cfg(pred: &[Tree]) -> String {
    let mut out = String::new();
    let mut i = 0;
    while i < pred.len() {
        match (&pred[i], pred.get(i + 1), pred.get(i + 2)) {
            (Tree::Tok(Tok::Ident(f)), Some(Tree::Tok(Tok::Punct('='))), Some(Tree::Tok(Tok::Str(v))))
                if f == "feature" =>
            {
                out.push_str(v);
                i += 3;
            }
            (Tree::Tok(Tok::Ident(f)), Some(Tree::Group('(', kids)), _) => {
                let _ = write!(out, "{f}({})", render_cfg(kids));
                i += 2;
            }
            (t, _, _) => {
                out.push_str(&render_tokens(std::slice::from_ref(t)));
                i += 1;
            }
        }
    }
    out
}

/// `cfg(test)` or `cfg(all(test, ..))`.
fn is_test_cfg(pred: &[Tree]) -> bool {
    match pred {
        [Tree::Tok(Tok::Ident(t))] => t == "test",
        [Tree::Tok(Tok::Ident(all)), Tree::Group('(', kids)] if all == "all" => {
            split_commas(kids).iter().any(|k| is_test_cfg(k))
        }
        _ => false,
    }
}

/// The upstream functions cited at the start of a doc line: one or more
/// backtick spans joined by `/`, `,`, `+`, `and` or `or`, optionally after
/// "The " or "Mutable ".
fn lead_citations(line: &str) -> Vec<String> {
    let mut s = line.trim();
    for prefix in ["The ", "Mutable "] {
        if let Some(r) = s.strip_prefix(prefix)
            && r.starts_with('`')
        {
            s = r;
        }
    }
    let mut out = Vec::new();
    while let Some(r) = s.strip_prefix('`') {
        let Some(end) = r.find('`') else { break };
        for name in span_citations(&r[..end]) {
            if !out.contains(&name) {
                out.push(name);
            }
        }
        s = r[end + 1..].trim_start();
        let next = ["/", ",", "+", "and ", "or "]
            .iter()
            .find_map(|sep| s.strip_prefix(sep))
            .map(str::trim_start);
        match next {
            Some(n) if n.starts_with('`') => s = n,
            _ => break,
        }
    }
    out
}

/// `(`lv_name`)` or `(`lv_name()`)` at the end of the first sentence, when
/// the C name ends with the Rust item name (`deinit` documented "Release an
/// unused default theme (`lv_theme_default_deinit`)."). A trailing span that
/// names another function only says which C call the item uses, as in
/// "A zeroed descriptor (`lv_memzero`)." on `GradDsc::new`.
fn trailing_citation(line: &str, item: &str) -> Option<String> {
    let line = line.trim();
    let sentence = line.split_once(". ").map_or(line, |(first, _)| first);
    let inner = sentence
        .strip_suffix('.')
        .unwrap_or(sentence)
        .strip_suffix("`)")?
        .rsplit_once("(`")?
        .1;
    if inner.contains('`') {
        return None;
    }
    let name = inner.strip_suffix("()").unwrap_or(inner);
    let named_after = name.strip_suffix(item).is_some_and(|stem| stem.ends_with('_'));
    (is_lv_fn_name(name) && named_after).then(|| name.to_string())
}

/// `lv_name()`, `lv_name(args)` and `lv_name_fmt/vfmt()` inside one backtick
/// span. A span holding other code (`lv_free(obj); return NULL;`,
/// `lv_ll_ins_tail(&subject->subs_ll)`) quotes C, it does not cite a port.
fn span_citations(span: &str) -> Vec<String> {
    let span = span.trim();
    let Some(paren) = span.find('(') else {
        return Vec::new();
    };
    if !span.ends_with(')') || [";", "->", "&", "="].iter().any(|c| span.contains(c)) {
        return Vec::new();
    }
    let mut depth = 0i32;
    for (k, c) in span[paren..].char_indices() {
        match c {
            '(' => depth += 1,
            ')' => depth -= 1,
            _ => {}
        }
        if depth == 0 && paren + k + 1 != span.len() {
            return Vec::new(); // `lv_a() + lv_b()`
        }
    }
    let mut parts = span[..paren].trim().split('/');
    let Some(first) = parts.next().filter(|f| is_lv_fn_name(f)) else {
        return Vec::new();
    };
    let mut out = vec![first.to_string()];
    for part in parts {
        if is_lv_fn_name(part) {
            out.push(part.to_string());
        } else if !part.is_empty()
            && part
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            && let Some((stem, _)) = first.rsplit_once('_')
        {
            out.push(format!("{stem}_{part}"));
        }
    }
    out
}

/// Every `lv_*()` cited in a doc sentence that says it is not ported.
fn collect_notes(docs: &[String], file: &str, idx: &mut RustIndex) {
    const NEGATIVE: &[&str] = &[
        "not ported",
        "not provided",
        "not exposed",
        "compiled out",
        "not implemented",
        "not supported",
    ];
    if docs.is_empty() {
        return;
    }
    let text = docs.join(" ");
    for sentence in text.split(". ") {
        let lower = sentence.to_lowercase();
        if !NEGATIVE.iter().any(|n| lower.contains(n)) {
            continue;
        }
        for (n, span) in sentence.split('`').enumerate() {
            if n % 2 == 1 {
                for name in span_citations(span) {
                    idx.notes.entry(name).or_default().insert(file.to_string());
                }
            }
        }
    }
}

