/// One upstream public function.
#[derive(Clone, Debug, PartialEq, Eq)]
struct CFunc {
    name: String,
    /// The `#if` conditions around the prototype (include guards and
    /// `__cplusplus` blocks removed), outermost first.
    guard: Vec<String>,
    /// `@deprecated` or a doc line starting with `DEPRECATED` in its doc
    /// comment, an `LV_DEPRECATED()` attribute, or an `api_map` alias.
    deprecated: bool,
    /// Takes a `va_list`.
    va_list: bool,
    /// The function a `#define lv_old lv_new` alias names.
    alias_of: Option<String>,
}

/// One upstream header and its functions in declaration order.
#[derive(Clone, Debug)]
struct Header {
    /// Path relative to `include/lvgl` (`src/widgets/...` for the `src` scan).
    path: String,
    funcs: Vec<CFunc>,
}

/// Marks the position of a `/** ... */` comment in the comment-free code.
const DOC_MARK: char = '\u{1}';

fn scan_upstream(root: &Path) -> Result<Vec<Header>> {
    let include = root.join(UPSTREAM_INCLUDE);
    let mut headers = Vec::new();
    for file in list_files(&include, "h")? {
        let text = std::fs::read_to_string(&file)?;
        let path = rel(&file, &include);
        headers.push(Header {
            path,
            funcs: parse_c_header(&text),
        });
    }
    let src = root.join(UPSTREAM_SRC_WIDGETS);
    if src.is_dir() {
        for file in list_files(&src, "h")? {
            let name = file.file_name().and_then(|n| n.to_str()).unwrap_or_default();
            let text = std::fs::read_to_string(&file)?;
            if !name.starts_with("lv_")
                || name.ends_with("_private.h")
                || rel(&file, &src).starts_with("objx_templ/")
                || text.contains("include/lvgl/lvgl.h")
            {
                continue;
            }
            let path = format!("src/widgets/{}", rel(&file, &src));
            headers.push(Header {
                path,
                funcs: parse_c_header(&text),
            });
        }
    }
    Ok(headers)
}

/// Every function of a header, in declaration order, first declaration wins.
fn parse_c_header(text: &str) -> Vec<CFunc> {
    let (code, docs) = strip_c_comments(text);
    let lines: Vec<&str> = code.split('\n').collect();
    let mut guards: Vec<Guard> = Vec::new();
    let mut funcs: Vec<CFunc> = Vec::new();
    let mut stmt = String::new();
    // One entry per open `{`: `true` for a real block, `false` for `extern "C" {`.
    let mut blocks: Vec<bool> = Vec::new();
    let mut doc_idx = 0usize;
    let mut pending_doc: Option<usize> = None;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    fn push(f: Option<CFunc>, funcs: &mut Vec<CFunc>) {
        if let Some(f) = f
            && !funcs.iter().any(|g| g.name == f.name)
        {
            funcs.push(f);
        }
    }
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        i += 1;
        if quote.is_none() && line.trim_start().starts_with('#') {
            let mut directive = line.trim().to_string();
            while directive.ends_with('\\') && i < lines.len() {
                directive.pop();
                directive.push(' ');
                directive.push_str(lines[i].trim());
                i += 1;
            }
            doc_idx += directive.matches(DOC_MARK).count();
            if squash(&directive).starts_with("#define") {
                pending_doc = None; // a doc comment of a macro
                push(
                    eval_c_alias(&directive.replace(DOC_MARK, " "), &guards),
                    &mut funcs,
                );
            }
            apply_directive(&directive.replace(DOC_MARK, " "), &mut guards);
            continue;
        }
        for ch in line.chars().chain(std::iter::once('\n')) {
            let top = !blocks.iter().any(|&b| b);
            if let Some(q) = quote {
                if top {
                    stmt.push(ch);
                }
                if escaped {
                    escaped = false;
                } else if ch == '\\' {
                    escaped = true;
                } else if ch == q || ch == '\n' {
                    quote = None;
                }
                continue;
            }
            match ch {
                DOC_MARK => {
                    if top {
                        pending_doc = Some(doc_idx);
                    }
                    doc_idx += 1;
                }
                '"' | '\'' => {
                    quote = Some(ch);
                    if top {
                        stmt.push(ch);
                    }
                }
                '{' => {
                    if top {
                        if squash(&stmt) == "extern \"C\"" {
                            blocks.push(false);
                            stmt.clear();
                            continue;
                        }
                        let doc = pending_doc.take().and_then(|k| docs.get(k)).map(String::as_str);
                        push(eval_c_statement(&stmt, &guards, doc), &mut funcs);
                        stmt.clear();
                    }
                    blocks.push(true);
                }
                '}' => {
                    blocks.pop();
                    if !blocks.iter().any(|&b| b) {
                        stmt.clear();
                    }
                }
                ';' if top => {
                    let doc = pending_doc.take().and_then(|k| docs.get(k)).map(String::as_str);
                    push(eval_c_statement(&stmt, &guards, doc), &mut funcs);
                    stmt.clear();
                }
                _ if top => stmt.push(ch),
                _ => {}
            }
        }
    }
    funcs
}

/// Removes comments. Each `/** */` doc comment becomes [`DOC_MARK`] and its
/// text is returned in order; newlines inside comments are kept so that
/// preprocessor lines stay on their own lines.
fn strip_c_comments(text: &str) -> (String, Vec<String>) {
    let c: Vec<char> = text.chars().collect();
    let at = |k: usize| c.get(k).copied().unwrap_or('\0');
    let mut out = String::with_capacity(text.len());
    let mut docs = Vec::new();
    let mut i = 0;
    while i < c.len() {
        match (c[i], at(i + 1)) {
            ('/', '/') => {
                while i < c.len() && c[i] != '\n' {
                    i += 1;
                }
            }
            ('/', '*') => {
                let start = i + 2;
                let mut j = start;
                while j < c.len() && !(c[j] == '*' && at(j + 1) == '/') {
                    j += 1;
                }
                let body: String = c[start..j.min(c.len())].iter().collect();
                if body.len() > 1
                    && body.starts_with('*')
                    && !body.starts_with("**")
                    && !body.starts_with("*<")
                {
                    docs.push(body[1..].to_string());
                    out.push(DOC_MARK);
                } else {
                    out.push(' ');
                }
                out.extend(body.chars().filter(|&ch| ch == '\n'));
                i = j + 2;
            }
            (q @ ('"' | '\''), _) => {
                out.push(q);
                i += 1;
                while i < c.len() && c[i] != q && c[i] != '\n' {
                    if c[i] == '\\' && i + 1 < c.len() {
                        out.push(c[i]);
                        i += 1;
                    }
                    out.push(c[i]);
                    i += 1;
                }
                if at(i) == q {
                    out.push(q);
                    i += 1;
                }
            }
            (ch, _) => {
                out.push(ch);
                i += 1;
            }
        }
    }
    (out, docs)
}

/// One open `#if`.
#[derive(Clone, Debug)]
struct Guard {
    cond: String,
    /// Include guards and `__cplusplus` blocks are not shown.
    hidden: bool,
}

impl Guard {
    fn new(cond: String) -> Self {
        let include_guard = cond
            .strip_prefix("!defined(")
            .and_then(|r| r.strip_suffix(')'))
            .is_some_and(|name| name.ends_with("_H"));
        let hidden = include_guard || cond.contains("__cplusplus");
        Self { cond, hidden }
    }
}

fn apply_directive(directive: &str, guards: &mut Vec<Guard>) {
    let body = directive.trim_start_matches('#').trim_start();
    let (kw, rest) = body.split_once(char::is_whitespace).unwrap_or((body, ""));
    let rest = squash(rest);
    match kw {
        "if" => guards.push(Guard::new(rest)),
        "ifdef" => guards.push(Guard::new(format!("defined({rest})"))),
        "ifndef" => guards.push(Guard::new(format!("!defined({rest})"))),
        "elif" | "elifdef" | "elifndef" => {
            let cond = match kw {
                "elifdef" => format!("defined({rest})"),
                "elifndef" => format!("!defined({rest})"),
                _ => rest,
            };
            if let Some(g) = guards.last_mut() {
                *g = Guard::new(cond);
            }
        }
        "else" => {
            if let Some(g) = guards.last_mut() {
                g.cond = format!("!({})", g.cond);
            }
        }
        "endif" => {
            guards.pop();
        }
        _ => {}
    }
}

fn visible_guards(guards: &[Guard]) -> Vec<String> {
    guards
        .iter()
        .filter(|g| !g.hidden)
        .map(|g| g.cond.clone())
        .collect()
}

/// `#define lv_old lv_new` or `#define lv_old(a, b) lv_new(b)`: a function
/// alias (the `api_map/` headers). Type aliases (`_t`) are not functions.
fn eval_c_alias(directive: &str, guards: &[Guard]) -> Option<CFunc> {
    let toks = c_tokens(directive);
    let rest = match toks.as_slice() {
        [hash, define, rest @ ..] if hash == "#" && define == "define" => rest,
        _ => return None,
    };
    let (name, mut body) = match rest {
        [name, rest @ ..] if is_lv_fn_name(name) && !name.ends_with("_t") => (name, rest),
        _ => return None,
    };
    // Parameters: `(` directly after the name.
    let params_follow = directive
        .split_once(name.as_str())
        .is_some_and(|(_, after)| after.starts_with('('));
    if params_follow {
        let close = body.iter().position(|t| t == ")")?;
        body = &body[close + 1..];
    }
    let target = match body {
        [target] => target,
        [target, open, .., close] if open == "(" && close == ")" => target,
        _ => return None,
    };
    if !is_lv_fn_name(target) || target.ends_with("_t") || target == name {
        return None;
    }
    if body.len() > 1 {
        // The call must span the whole body: `lv_a(x) + lv_b(y)` is not an alias.
        let mut depth = 0i32;
        for (k, t) in body[1..].iter().enumerate() {
            match t.as_str() {
                "(" => depth += 1,
                ")" => depth -= 1,
                _ => {}
            }
            if depth == 0 && k + 2 != body.len() {
                return None;
            }
        }
    }
    Some(CFunc {
        name: name.clone(),
        guard: visible_guards(guards),
        deprecated: true,
        va_list: false,
        alias_of: Some(target.clone()),
    })
}

/// `@deprecated`, or a doc line that starts with the word `DEPRECATED`
/// (`DEPRECATED, use lv_scale_set_section_range instead.`).
fn doc_deprecated(doc: &str) -> bool {
    doc.contains("@deprecated")
        || doc.lines().any(|l| {
            l.trim_start()
                .trim_start_matches('*')
                .trim_start()
                .strip_prefix("DEPRECATED")
                .is_some_and(|r| !r.starts_with(|c: char| c.is_ascii_alphanumeric() || c == '_'))
        })
}

/// A top-level declaration (text up to `;` or `{`) as a function, if it is one.
fn eval_c_statement(stmt: &str, guards: &[Guard], doc: Option<&str>) -> Option<CFunc> {
    let toks = c_tokens(stmt);
    if toks.iter().any(|t| t == "typedef") {
        return None;
    }
    let mut depth = 0i32;
    for (k, t) in toks.iter().enumerate() {
        match t.as_str() {
            "(" => depth += 1,
            ")" => depth -= 1,
            "=" if depth == 0 => return None,
            _ => {}
        }
        if depth != 0 || !is_lv_fn_name(t) || toks.get(k + 1).map(String::as_str) != Some("(") {
            continue;
        }
        if !toks[..k].iter().any(|t| is_c_ident(t)) {
            return None; // a macro call, not a declaration
        }
        let mut d = 0;
        let mut va_list = false;
        for p in &toks[k + 1..] {
            match p.as_str() {
                "(" => d += 1,
                ")" => {
                    d -= 1;
                    if d == 0 {
                        break;
                    }
                }
                "va_list" => va_list = true,
                _ => {}
            }
        }
        let deprecated = doc.is_some_and(doc_deprecated) || toks[..k].iter().any(|t| t == "LV_DEPRECATED");
        return Some(CFunc {
            name: t.clone(),
            guard: visible_guards(guards),
            deprecated,
            va_list,
            alias_of: None,
        });
    }
    None
}

fn c_tokens(s: &str) -> Vec<String> {
    let c: Vec<char> = s.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let ch = c[i];
        if ch.is_whitespace() {
            i += 1;
        } else if ch.is_ascii_alphanumeric() || ch == '_' {
            let start = i;
            while i < c.len() && (c[i].is_ascii_alphanumeric() || c[i] == '_') {
                i += 1;
            }
            out.push(c[start..i].iter().collect());
        } else if ch == '"' || ch == '\'' {
            let start = i;
            i += 1;
            while i < c.len() && c[i] != ch {
                i += if c[i] == '\\' { 2 } else { 1 };
            }
            i = (i + 1).min(c.len());
            out.push(c[start..i].iter().collect());
        } else {
            out.push(ch.to_string());
            i += 1;
        }
    }
    out
}

fn is_c_ident(t: &str) -> bool {
    t.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
}

/// `lv_` followed by lower-case letters, digits and underscores.
fn is_lv_fn_name(t: &str) -> bool {
    t.strip_prefix("lv_").is_some_and(|r| {
        !r.is_empty()
            && r.chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    })
}

