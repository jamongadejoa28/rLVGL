/// `lv_palette_main()`: the main colour of a palette (black if invalid).
pub fn main(p: Palette) -> Color {
    let i = p as usize;
    if i >= Palette::Last as usize {
        crate::misc::check_arg_failed("invalid palette");
        return Color::black();
    }
    MAIN[i]
}

/// `lv_palette_lighten()`: a lighter colour, `lvl` in `1..=5` (black if invalid).
pub fn lighten(p: Palette, lvl: u8) -> Color {
    let i = p as usize;
    if i >= Palette::Last as usize {
        crate::misc::check_arg_failed("invalid palette");
        return Color::black();
    }
    if lvl < 1 || lvl > 5 {
        crate::misc::check_arg_failed("invalid level, must be 1..5");
        return Color::black();
    }
    LIGHTEN[i][(lvl - 1) as usize]
}

/// `lv_palette_darken()`: a darker colour, `lvl` in `1..=4` (black if invalid).
pub fn darken(p: Palette, lvl: u8) -> Color {
    let i = p as usize;
    if i >= Palette::Last as usize {
        crate::misc::check_arg_failed("invalid palette");
        return Color::black();
    }
    if lvl < 1 || lvl > 4 {
        crate::misc::check_arg_failed("invalid level, must be 1..4");
        return Color::black();
    }
    DARKEN[i][(lvl - 1) as usize]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn palette_values() {
        assert_eq!(main(Palette::Red), Color::hex(0xF44336));
        assert_eq!(main(Palette::Grey), Color::hex(0x9E9E9E));
        assert_eq!(lighten(Palette::Blue, 1), Color::hex(0x42A5F5));
        assert_eq!(lighten(Palette::Blue, 5), Color::hex(0xE3F2FD));
        assert_eq!(darken(Palette::Blue, 4), Color::hex(0x0D47A1));
        assert_eq!(darken(Palette::Grey, 1), Color::hex(0x757575));
        assert_eq!(Palette::Last as u8, 19);
        assert_eq!(Palette::None as u8, 0xFF);
    }

    #[test]
    fn table_corners_match_lv_palette_c() {
        // First / last entries of every table of src/misc/lv_palette.c.
        assert_eq!(main(Palette::Pink), Color::hex(0xE91E63));
        assert_eq!(main(Palette::BlueGrey), Color::hex(0x607D8B));
        assert_eq!(lighten(Palette::Red, 1), Color::hex(0xEF5350));
        assert_eq!(lighten(Palette::Grey, 5), Color::hex(0xFAFAFA));
        assert_eq!(lighten(Palette::DeepOrange, 5), Color::hex(0xFBE9E7));
        assert_eq!(darken(Palette::Red, 1), Color::hex(0xE53935));
        assert_eq!(darken(Palette::Grey, 4), Color::hex(0x212121));
        assert_eq!(darken(Palette::Amber, 4), Color::hex(0xFF6F00));
        assert_eq!(MAIN.len(), Palette::Last as usize);
        assert_eq!(LIGHTEN.len(), Palette::Last as usize);
        assert_eq!(DARKEN.len(), Palette::Last as usize);
    }

    #[cfg(not(feature = "check-arg-panic"))]
    #[test]
    fn invalid_arguments_yield_black() {
        assert_eq!(main(Palette::Last), Color::black());
        assert_eq!(main(Palette::None), Color::black());
        assert_eq!(lighten(Palette::Red, 0), Color::black());
        assert_eq!(lighten(Palette::Red, 6), Color::black());
        assert_eq!(darken(Palette::Red, 5), Color::black());
    }
}
